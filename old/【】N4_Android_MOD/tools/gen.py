class B:
    def __init__(self):
        self.lines = []
        self.d = 1

    def sec(self, name):
        if self.lines:
            self.lines.append("")
        self.lines.append("@" + name)
        self.d = 1

    def __call__(self, *cmds):
        for c in cmds:
            self.lines.append("    " * self.d + c)

    def IF(self, cond):
        self("if," + cond)
        self("{")
        self.d += 1

    def ELSE(self):
        self.d -= 1
        self("}else{")
        self.d += 1

    def END(self):
        self.d -= 1
        self("}")

    def text(self):
        return "\n".join(self.lines) + "\n"


