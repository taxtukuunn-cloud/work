def street(sec_names):
    out = []
    for s in sec_names:
        out += ["", f"@{s}_街バトル", f"    イベント実行,{s}"]
    return out


OUTSIDE = ("@フィールドイベント", "@敗北再生", "@前回続き", "@敗北_")


def fix_outside_battle(lines):
    """戦闘の外で流す場面の手直し（N11・N13・N4の実機確認より）
    - 主人公の話者は `相手` が決まらないので `相手プレイヤー`
    - 敗北後の画面は暗転しているので、画像を出したら `フェードイン,1`"""
    out, inside, fade = [], False, False
    for l in lines:
        st = l.strip()
        if st.startswith("@"):
            inside = st.startswith(OUTSIDE) and not st.endswith("_街バトル")
            fade = inside or st == "@オナニー"
            out.append(l)
            continue
        if inside and st == "話者,相手":
            l = l.replace("話者,相手", "話者,相手プレイヤー")
        out.append(l)
        if fade and st.startswith("画像,"):
            out.append(l[: len(l) - len(l.lstrip())] + "フェードイン,1")
    return out


def write(path, lines):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write("\r\n".join(l.replace("\n", "\\n") for l in lines) + "\r\n")


