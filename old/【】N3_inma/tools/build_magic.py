def magic(n, name, typ, rare, ex, flavor, head, case1, case2=None, trap=False, target=None, cont=False):
    L = ["default", "@初期設定"]
    ini = [f"&カード名,{name}", f"&カード画像,{img(f'magic_{n}')}", "属性設定,闇属性",
           f"タイプ設定,{typ}", f"レアリティ設定,{rare}", f"&魔法CG,{img(f'magic_{n}')}"]
    if trap:
        ini += [f"効果設定,1,forceTrigger,{ex}", "誘発効果設定,1,onAttack",
                "効果条件設定,1,トリガー能動カード.所属,!=,自分所属"]
    else:
        ini += [f"効果設定,1,play,{ex}"]
    if target:
        ini += [f"効果ターゲット設定,1,{target}"]
    if cont:
        ini += ["効果設定,2,forceTrigger,自分のターン終了時に発動。3回発動すると自壊する。",
                "誘発効果設定,2,エンドフェイズ開始時", "効果条件設定,2,Now自分ターン,==,true",
                ]
    ini += [f"効果設定,0,explain,{flavor}"]
    L += ind(ini, 4)
    L += ["", "@効果", "switch,効果ID", "case,1", "{"]
    L += ind(["話者変更,自分プレイヤー", "画像表示,&魔法CG,1"] + head + case1) + ["}"]
    if case2:
        L += ["case,2", "{"] + ind(case2) + ["}"]
    L += townbattle(["効果"])
    write_card(f"/home/claude/Inma/out/Card/Inma_magic_{n}.txt", L)

