def convert(lines, speaker):
    out = []
    for l in lines:
        if l == "話者変更,自分":
            out.append(f"話者,%{speaker}" if speaker else "話者,自分")
        elif l == "話者変更,相手":
            out.append("話者,相手プレイヤー")
        elif l.startswith("画像表示,#Inma/Inma_lose_"):
            key = l.split("Inma_lose_")[1].split(".png")[0]
            out.append(f"画像,&敗北CG_{key},1")
        elif l.startswith("画像表示,"):
            out.append("画像," + l[len("画像表示,"):])
        else:
            out.append(l)
    return out

