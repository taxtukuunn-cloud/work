def sec_name(route, who):
    return f"敗北_{route}_{who}" if who.startswith("m") else f"敗北_{route}"

def dispatcher(self_card):
    b = ["@敗北後", "if,$$CrossCafe_再生済,==,0", "{",
         " $$CrossCafe_再生済,=,1",
         " BGM,&BGM_敗北",
         " $経路,=,自分プレイヤー.$敗北経路",
         " if,$経路,==,0", " {", "  $経路,=,1", " }",
         " $責め手,=,自分プレイヤー.$最後の責め手",
         " if,$責め手,==,0", " {", "  $責め手,=,1", " }",
         " $技,=,自分プレイヤー.$最後の技"]
    for ri, r in enumerate(ROUTES, 1):
        b += [f" if,$経路,==,{ri}", " {"]
        for wi, w in enumerate(WHO, 1):
            card = CARD_OF[w]
            call = (f"イベント実行,{sec_name(r, w)}" if card == self_card
                    else f"外部イベント実行,Card/{C}_{card},{sec_name(r, w)}")
            b += [f"  if,$責め手,==,{wi}", "  {", "   " + call]
            # 弱点付与
            if r == "onani":
                b += ["   主人公攻撃タイプ弱点付与,強制自慰,50"]
            elif len(TYPES[w]) == 1:
                b += [f"   主人公攻撃タイプ弱点付与,{TYPES[w][0]},50"]
            else:
                b += ["   if,$技,==,2", "   {", f"    主人公攻撃タイプ弱点付与,{TYPES[w][1]},50",
                      "   }else{", f"    主人公攻撃タイプ弱点付与,{TYPES[w][0]},50", "   }"]
            b += ["  }"]
        b += [" }"]
    b += [" 画像全削除",
          " $$CrossCafe_敗北回数,+=,1",
          " $$CrossCafe_前回敗北経路,=,$経路",
          " $$CrossCafe_前回最後の責め手,=,$責め手",
          " フラッシュ,白", " 説明,GAME OVER", "}"]
    return b

def scen_sections(whos):
    out = []
    for w in whos:
        for r in ROUTES:
            out += ["", "@" + sec_name(r, w)] + scen(r, w)
    return out

def receivers(names):
    out = []
    for n in names:
        out += ["", f"@{n}_街バトル", f"    イベント実行,{n}"]
    return out

def sections_of(lines):
    return [l[1:] for l in lines if l.startswith("@") and not l.endswith("_街バトル")
            and l[1:] not in ("初期設定",)]

